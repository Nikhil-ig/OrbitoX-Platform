export function icon(name: IconName, options: IconOptions = {}): string {
  const size = options.size || 16;
  const strokeWidth = options.strokeWidth || 2;
  const color = options.color || 'currentColor';
  const className = options.className ? ` class="${options.className}"` : '';
  const style = options.style ? ` style="${options.style}"` : '';
  const aria = options.ariaLabel
    ? ` role="img" aria-label="${options.ariaLabel}"`
    : ' aria-hidden="true"';

  const paths = ICONS_PATH_MAP[name] || ICONS_PATH_MAP.info;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"${className}${style}${aria}>${paths}</svg>`;
}
