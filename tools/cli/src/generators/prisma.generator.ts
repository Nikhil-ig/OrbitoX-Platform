import * as fs from 'fs';
import * as path from 'path';

/**
 * Generates a Prisma schema from the OrbitoX manifest entities.
 */
export function generatePrismaSchema(projectDir: string, manifest: any): void {
  const prismaDir = path.join(projectDir, 'prisma');
  if (!fs.existsSync(prismaDir)) {
    fs.mkdirSync(prismaDir, { recursive: true });
  }

  const schemaPath = path.join(prismaDir, 'schema.prisma');
  
  let schema = `// Auto-generated by OrbitoX CLI
generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

`;

  const enums = new Map<string, string[]>();

  for (const entity of manifest.entities) {
    const modelName = toPascalCase(entity.id);
    schema += `model ${modelName} {\n`;
    schema += `  id          String   @id @default(cuid())\n`;
    schema += `  contextId   String   // OrbitoX Multi-Tenancy Scope\n`;
    
    for (const field of entity.fields || []) {
      const fieldName = field.name;
      const isOptional = field.required ? '' : '?';
      let prismaType = 'String';

      switch (field.type) {
        case 'text':
          prismaType = 'String';
          break;
        case 'number':
          prismaType = 'Float';
          break;
        case 'boolean':
          prismaType = 'Boolean';
          break;
        case 'enum':
          prismaType = `${modelName}${toPascalCase(fieldName)}Enum`;
          enums.set(prismaType, field.options || []);
          break;
        case 'date':
          prismaType = 'DateTime';
          break;
      }

      let defaultAttr = '';
      if (field.default !== undefined) {
        if (field.type === 'boolean') {
          defaultAttr = ` @default(${field.default})`;
        } else if (field.type === 'number') {
          defaultAttr = ` @default(${field.default})`;
        } else if (field.type === 'text') {
          defaultAttr = ` @default("${field.default}")`;
        }
      }

      schema += `  ${fieldName.padEnd(12)} ${prismaType}${isOptional}${defaultAttr}\n`;
    }

    schema += `  createdAt   DateTime @default(now())\n`;
    schema += `  updatedAt   DateTime @updatedAt\n`;
    schema += `}\n\n`;
  }

  for (const [enumName, options] of enums.entries()) {
    schema += `enum ${enumName} {\n`;
    for (const opt of options) {
      schema += `  ${opt.toUpperCase().replace(/[^A-Z0-9]/g, '_')}\n`;
    }
    schema += `}\n\n`;
  }

  fs.writeFileSync(schemaPath, schema, 'utf8');
  console.log(`   ✅ Auto-generated Prisma Schema: prisma/schema.prisma`);
}

function toPascalCase(str: string): string {
  return str.split(/[-_]/).map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
}
