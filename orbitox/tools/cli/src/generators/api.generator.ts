import * as fs from 'fs';
import * as path from 'path';

/**
 * Generates secure Express API routes from the OrbitoX manifest entities.
 */
export function generateApiRoutes(projectDir: string, manifest: any): void {
  const routesDir = path.join(projectDir, 'src', 'api', 'routes');
  if (!fs.existsSync(routesDir)) {
    fs.mkdirSync(routesDir, { recursive: true });
  }

  let indexFile = `// Auto-generated by OrbitoX CLI
import { Router } from 'express';\n\nconst apiRouter = Router();\n\n`;

  for (const entity of manifest.entities) {
    const routeFileName = `${entity.id}.routes.ts`;
    const routePath = path.join(routesDir, routeFileName);
    
    const pascalName = toPascalCase(entity.id);
    const varName = toCamelCase(entity.id);
    const routeName = entity.id.replace(/_/g, '-');
    const permissionScope = manifest.id ? `${manifest.id}.${entity.id}` : entity.id;

    const routeCode = `// Auto-generated by OrbitoX CLI
import { Router } from 'express';
// import { rbacService } from '../../services/orbitox';
// import { prisma } from '../../db';

export const ${varName}Router = Router();

// Middleware placeholder for extracting user/context
const authMock = (req: any, res: any, next: any) => {
  req.user = { id: 'mock_user' };
  req.context = { id: 'mock_context' };
  next();
};

${varName}Router.use(authMock);

// GET ALL
${varName}Router.get('/', async (req: any, res: any) => {
  try {
    // Zero-Trust Security Gate
    // await rbacService.authorize({ userId: req.user.id, contextId: req.context.id, permission: '${permissionScope}.read' });
    
    // const items = await prisma.${varName}.findMany({ where: { contextId: req.context.id } });
    res.json({ message: 'GET all ${pascalName}s (Mock)', items: [] });
  } catch (error: any) {
    res.status(403).json({ error: error.message });
  }
});

// GET ONE
${varName}Router.get('/:id', async (req: any, res: any) => {
  try {
    // await rbacService.authorize({ userId: req.user.id, contextId: req.context.id, permission: '${permissionScope}.read' });
    // const item = await prisma.${varName}.findUnique({ where: { id: req.params.id, contextId: req.context.id } });
    res.json({ message: \`GET ${pascalName} \${req.params.id} (Mock)\`, item: null });
  } catch (error: any) {
    res.status(403).json({ error: error.message });
  }
});

// CREATE
${varName}Router.post('/', async (req: any, res: any) => {
  try {
    // Zero-Trust Security Gate
    // await rbacService.authorize({ userId: req.user.id, contextId: req.context.id, permission: '${permissionScope}.create' });
    
    // const item = await prisma.${varName}.create({ data: { ...req.body, contextId: req.context.id } });
    res.status(201).json({ message: 'CREATED ${pascalName} (Mock)', item: req.body });
  } catch (error: any) {
    res.status(403).json({ error: error.message });
  }
});

// UPDATE
${varName}Router.patch('/:id', async (req: any, res: any) => {
  try {
    // await rbacService.authorize({ userId: req.user.id, contextId: req.context.id, permission: '${permissionScope}.update' });
    // const item = await prisma.${varName}.update({ where: { id: req.params.id, contextId: req.context.id }, data: req.body });
    res.json({ message: \`UPDATED ${pascalName} \${req.params.id} (Mock)\`, item: req.body });
  } catch (error: any) {
    res.status(403).json({ error: error.message });
  }
});

// DELETE
${varName}Router.delete('/:id', async (req: any, res: any) => {
  try {
    // await rbacService.authorize({ userId: req.user.id, contextId: req.context.id, permission: '${permissionScope}.delete' });
    // await prisma.${varName}.delete({ where: { id: req.params.id, contextId: req.context.id } });
    res.status(204).send();
  } catch (error: any) {
    res.status(403).json({ error: error.message });
  }
});
`;

    fs.writeFileSync(routePath, routeCode, 'utf8');
    console.log(`   ✅ Auto-generated API Route: src/api/routes/${routeFileName}`);

    indexFile += `import { ${varName}Router } from './${entity.id}.routes';\n`;
    indexFile += `apiRouter.use('/${routeName}s', ${varName}Router);\n\n`;
  }

  indexFile += `export default apiRouter;\n`;
  fs.writeFileSync(path.join(routesDir, 'index.ts'), indexFile, 'utf8');
  console.log(`   ✅ Auto-generated Router Index: src/api/routes/index.ts`);
}

function toPascalCase(str: string): string {
  return str.split(/[-_]/).map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
}

function toCamelCase(str: string): string {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}
